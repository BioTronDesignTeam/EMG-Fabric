"""Regenerate the golden packets checked by BOTH the C and the Python tests.

    python gen_golden.py   # writes firmware/prototype/test/golden/host_packets_v2.txt

Only rerun after an intentional protocol change. The file is committed, so an
accidental change in either decoder shows up as a test failure.

Format: one case per line, space-separated key=value. Lists are comma-separated, bytes are hex.
"""

from __future__ import annotations

from pathlib import Path

import emg_protocol as p

OUT = Path(__file__).resolve().parents[2] / "firmware" / "prototype" / "test" / "golden" / "host_packets_v2.txt"


def ints(xs) -> str:
    return ",".join(str(x) for x in xs)


def main() -> None:
    lines = [
        "# Golden host packets, protocol v2. GENERATED by Software/prototype/gen_golden.py - do not edit.",
        "# Checked by firmware/prototype/test/test_host_packet and Software/prototype/test_protocol.py.",
        "# valid=1: must decode to type/seq/payload (+ decoded fields). valid=0: must be rejected.",
        "# stream=1: a byte stream; expect_seqs = packets found, expect_crc_errors = CRC failures.",
    ]

    def case(name: str, ptype: int, seq: int, payload: bytes, extra: str) -> bytes:
        pkt = p.encode_packet(ptype, seq, payload)
        lines.append(f"case={name} valid=1 type={ptype} seq={seq} payload={payload.hex()} {extra} hex={pkt.hex()}".replace("  ", " "))
        return pkt

    # Slots 1 and 3 connected (mask 0b101). Slot 0's counter wraps 4095 -> 0.
    d = p.Data(1000, {
        0: p.SlotSamples(p.FLAG_COUNTER, 4090, [(4090 + i) & 0xFFF for i in range(10)]),
        2: p.SlotSamples(p.FLAG_SYNTHETIC | p.FLAG_OVERRUN, 7, [-5000, -1, 0, 1, 2048, 4095, 32767, -32768, 100, 200]),
    })
    pkt_data = case(
        "data_two_slots", p.PKT_DATA, 7, p.encode_data(d),
        f"tick=1000 mask=5 "
        f"s0_flags={d.slots[0].flags} s0_first={d.slots[0].first_frame} s0_samples={ints(d.slots[0].samples)} "
        f"s2_flags={d.slots[2].flags} s2_first={d.slots[2].first_frame} s2_samples={ints(d.slots[2].samples)}",
    )

    pkt_empty = case("data_no_slots", p.PKT_DATA, 65535, p.encode_data(p.Data(0xFFFFFFF0)), "tick=4294967280 mask=0")

    st = p.Status(123456, 0b0011, [p.SlotStatus(1, 2, 3, 2), p.SlotStatus(0, 0, 0, 4), p.SlotStatus(0, 0, 0, 0), p.SlotStatus(9, 8, 7, 3)])
    case(
        "status", p.PKT_STATUS, 300, p.encode_status(st),
        "uptime=123456 present=3 crc_errors=1,0,0,9 gaps=2,0,0,8 overruns=3,0,0,7 last_flags=2,4,0,3",
    )

    case("log_text", p.PKT_LOG, 1, b"slot 1 connected", "")
    case("cmd_reset_stats", p.PKT_CMD, 9, p.encode_cmd(p.CMD_RESET_STATS), "")

    bad = bytearray(pkt_data)
    bad[-1] ^= 0xFF
    lines.append(f"case=bad_crc valid=0 hex={bytes(bad).hex()}")
    old = bytearray(pkt_data)
    old[2] = 1
    lines.append(f"case=old_version valid=0 hex={bytes(old).hex()}")

    # Boot text, a fake sync pair, a good packet, a corrupted one, a truncated header, a good one.
    stream = b"ets Jun  8 2016\r\n" + b"\xAA\x55\x07" + pkt_data + bytes(bad) + b"\xAA\x55\x02\x01" + pkt_empty
    parser = p.PacketParser()
    got = parser.feed(stream)
    assert [g.seq for g in got] == [7, 65535], got
    lines.append(
        f"case=stream_resync stream=1 expect_seqs={ints(g.seq for g in got)} "
        f"expect_crc_errors={parser.crc_errors} hex={stream.hex()}"
    )

    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
